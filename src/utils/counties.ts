// Function to find the county for a city or municipality query
export function findCountyForCity(query: string): { county: string; matchedCity: string } | null {
    const clean = query.trim().toLowerCase();
    if (clean.length < 3) return null;

    // 1. Direct match
    if (NORWEGIAN_CITIES_TO_COUNTY[clean]) {
        return { county: NORWEGIAN_CITIES_TO_COUNTY[clean], matchedCity: clean };
    }

    // 2. Starts with query (e.g. "lilleham" -> "lillehammer")
    for (const [city, county] of Object.entries(NORWEGIAN_CITIES_TO_COUNTY)) {
        if (city.startsWith(clean)) {
            return { county, matchedCity: city };
        }
    }

    return null;
}
